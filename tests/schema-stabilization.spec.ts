async function readStabilizationCatalog(db: PGlite) {
  const columns = (await db.query<{
    table_name: string;
    column_name: string;
    is_nullable: string;
    column_default: string | null;
  }>(`
    select table_name, column_name, is_nullable, column_default
    from information_schema.columns
    where (table_name = 'cards' and column_name = 'client_request_id')
       or (table_name = 'attachments' and column_name in ('state', 'updated_at'))
    order by table_name, column_name;
  `)).rows;
  const functions = (await db.query<{
    proname: string;
    prosecdef: boolean;
    empty_search_path: boolean;
    definition: string;
  }>(`
    select proname, prosecdef,
      coalesce('search_path=""' = any(proconfig), false) as empty_search_path,
      pg_get_functiondef(oid) as definition
    from pg_proc
    where pronamespace = 'public'::regnamespace
      and proname in (
        'consume_ai_daily_quota',
        'enforce_focus_limit',
        'lock_attachment_consistency',
        'reorder_attachments'
      )
    order by proname;
  `)).rows.map((row) => ({ ...row, definition: normalizeSqlDefinition(row.definition) }));
  const triggers = (await db.query<{
    table_name: string;
    trigger_name: string;
    definition: string;
  }>(`
    select relation.relname as table_name,
      trigger.tgname as trigger_name,
      pg_get_triggerdef(trigger.oid, true) as definition
    from pg_trigger as trigger
    join pg_class as relation on relation.oid = trigger.tgrelid
    where relation.relnamespace = 'public'::regnamespace
      and not trigger.tgisinternal
      and trigger.tgname in (
        'attachments_lock_consistency',
        'attachments_touch_updated_at',
        'cards_enforce_focus_limit',
        'cards_lock_attachment_consistency'
      )
    order by relation.relname, trigger.tgname;
  `)).rows.map((row) => ({ ...row, definition: normalizeSqlDefinition(row.definition) }));
  const indexes = (await db.query<{ indexname: string; indexdef: string }>(`
    select indexname, indexdef
    from pg_indexes
    where schemaname = 'public'
      and indexname = 'cards_owner_client_request_idx';
  `)).rows.map((row) => ({ ...row, indexdef: normalizeSqlDefinition(row.indexdef) }));
  const relations = (await db.query<{ relname: string; relrowsecurity: boolean }>(`
    select relname, relrowsecurity
    from pg_class
    where relnamespace = 'public'::regnamespace
      and relname = 'ai_usage_daily';
  `)).rows;
  const policies = (await db.query<{
    tablename: string;
    policyname: string;
    cmd: string;
    qual: string | null;
    with_check: string | null;
  }>(`
    select tablename, policyname, cmd, qual, with_check
    from pg_policies
    where schemaname = 'public'
      and tablename = 'attachments'
    order by policyname;
  `)).rows.map((row) => ({
    ...row,
    qual: normalizeSqlDefinition(row.qual),
    with_check: normalizeSqlDefinition(row.with_check),
  }));
  const privileges = (await db.query<{
    authenticated: boolean;
    anon: boolean;
    service_role: boolean;
  }>(`
    select
      has_function_privilege('authenticated', 'public.consume_ai_daily_quota(uuid, integer)', 'execute') as authenticated,
      has_function_privilege('anon', 'public.consume_ai_daily_quota(uuid, integer)', 'execute') as anon,
      has_function_privilege('service_role', 'public.consume_ai_daily_quota(uuid, integer)', 'execute') as service_role;
  `)).rows;
  return { columns, functions, triggers, indexes, relations, policies, privileges };
}

async function assumeRole(db: PGlite, role: "authenticated" | "service_role", userId = ALICE_ID) {
  await db.exec(`
    select set_config('request.jwt.claim.sub', '${userId}', false);
    set role ${role};
  `);
}

async function resetRole(db: PGlite) {
  await db.exec("reset role; select set_config('request.jwt.claim.sub', '', false);");
}

async function readAdvisoryLocks(db: PGlite) {
  return (await db.query<{
    classid: number;
    objid: number;
    objsubid: number;
    mode: string;
  }>(`
    select classid, objid, objsubid, mode
    from pg_locks
    where locktype = 'advisory'
      and pid = pg_backend_pid()
      and granted
    order by classid, objid, objsubid, mode;
  `)).rows;
}

